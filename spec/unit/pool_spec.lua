describe("Pool", function()
	local randomizer

	setup(function()
		randomizer = require("randomizer")
	end)

	describe("construction", function()
		it("should wrap a table in a new list", function()
			local pool = randomizer.pool({ 1, 2, 3 })
			assert.is_true(randomizer.isPool(pool))
			assert.are.equal(3, pool.pool:size())
			assert.are.equal(0, pool.used:size())
			assert.is_false(pool.consumable)
		end)

		it("should copy an existing list so draws do not mutate the source", function()
			randomizer.setSeed(1)
			local list = randomizer.list({ "a", "b" })
			local pool = randomizer.pool(list, { consumable = true })
			assert.are_not.equal(list, pool.pool)
			assert.are_not.equal(list.items, pool.pool.items)
			pool:draw()
			assert.are.equal(2, list:size())
			assert.are.equal(1, pool.pool:size())
		end)

		it("should honor consumable in pool options", function()
			local pool = randomizer.pool({ 1 }, { consumable = true })
			assert.is_true(pool.consumable)
		end)
	end)

	describe("draw", function()
		it("should sample with replacement when not consumable", function()
			randomizer.setSeed(42)
			local pool = randomizer.pool({ 1, 2 })
			pool:draw()
			pool:draw()
			assert.are.equal(2, pool.pool:size())
			assert.are.equal(0, pool.used:size())
		end)

		it("should consume without replacement when consumable", function()
			randomizer.setSeed(42)
			local pool = randomizer.pool({ "A", "B", "C" }, { consumable = true })
			local seen = {}
			for _ = 1, 3 do
				table.insert(seen, pool:draw())
			end
			assert.are.equal(0, pool.pool:size())
			assert.are.equal(3, pool.used:size())
			table.sort(seen)
			assert.are.same({ "A", "B", "C" }, seen)
		end)

		it("should recycle used items when consumable pool is empty", function()
			randomizer.setSeed(7)
			local pool = randomizer.pool({ 1, 2 }, { consumable = true })
			pool:draw()
			pool:draw()
			local third = pool:draw()
			assert.is_true(third == 1 or third == 2)
			assert.are.equal(1, pool.pool:size())
			assert.are.equal(1, pool.used:size())
		end)

		it("should return nil when exhausted and allowExhausted is true", function()
			local pool = randomizer.pool(randomizer.list({}), { consumable = true })
			assert.is_nil(pool:draw(true))
		end)

		it("should error when exhausted and allowExhausted is false", function()
			local pool = randomizer.pool(randomizer.list({}), { consumable = true })
			assert.has_error(function()
				pool:draw()
			end)
		end)
	end)
end)
